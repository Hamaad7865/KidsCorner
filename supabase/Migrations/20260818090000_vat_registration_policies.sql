-- VAT settings are mutated only by set_vat_policy. Suppressing their ordinary
-- row-trigger entries lets the RPC write one coherent old/new activity event.
create or replace function public.audit_settings()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
    if new.key in ('vat_enabled', 'vat_rate', 'vat_number') then
        return new;
    end if;

    perform public.log_audit(
        'setting.changed', 'setting', new.key,
        pg_catalog.format('%s changed', new.key),
        pg_catalog.jsonb_build_object('key', new.key, 'from', old.value, 'to', new.value)
    );
    return new;
end;
$$;

do $$
declare
    v_configured_rate numeric(7,6);
    v_vat_number text;
    v_legacy_id bigint;
begin
    select prepared.configured_rate, prepared.vat_number
      into v_configured_rate, v_vat_number
      from private.resolve_vat_policy_preparation(
          (select value from public.settings where key = 'vat_rate'),
          (select value from public.settings where key = 'vat_number')
      ) as prepared;

    insert into public.vat_policies (
        enabled, configured_rate, vat_number, is_legacy, created_by
    ) values (
        true, v_configured_rate, v_vat_number, true, null
    )
    returning id into v_legacy_id;

    update public.sales
       set vat_policy_id = v_legacy_id,
           vat_enabled = true,
           vat_rate = v_configured_rate,
           vat_number = v_vat_number;

    update public.credit_notes cn
       set vat_policy_id = s.vat_policy_id,
           vat_enabled = s.vat_enabled,
           vat_rate = s.vat_rate,
           vat_number = s.vat_number
      from public.sales s
     where s.id = cn.sale_id;

    update public.purchases
       set vat_policy_id = v_legacy_id,
           vat_enabled = true,
           vat_rate = v_configured_rate,
           vat_amount = round(total_amount - total_amount / (1 + v_configured_rate), 2)
     where status = 'received';

    update public.z_reports
       set vat_identity_snapshot = jsonb_build_array(
           jsonb_build_object(
               'policyId', v_legacy_id,
               'rate', v_configured_rate,
               'vatNumber', v_vat_number
           )
       );

    -- Highest id is the current policy. Start disabled without discarding a
    -- valid rate/number prepared before registration is enabled.
    insert into public.vat_policies (
        enabled, configured_rate, vat_number, is_legacy, created_by
    ) values (
        false, v_configured_rate, v_vat_number, false, null
    );

    insert into public.settings (key, value) values
        ('vat_enabled', 'false'::jsonb),
        ('vat_rate', to_jsonb(v_configured_rate)),
        ('vat_number', coalesce(to_jsonb(v_vat_number), 'null'::jsonb))
    on conflict (key) do update set value = excluded.value;
end;
$$;

