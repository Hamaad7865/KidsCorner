-- ============================================================
-- Kids Corner — immutable VAT registration policies
--
-- A policy row is an append-only fiscal decision. Documents retain the exact
-- policy identity and values in force when they were created; settings are
-- only the prepared pointer values used to create the next policy.
-- ============================================================

begin;

create schema if not exists private;
revoke all on schema private from public, anon, authenticated, service_role;

create table public.vat_policies (
    id                bigint generated by default as identity primary key,
    enabled           boolean not null,
    configured_rate   numeric(7,6) not null,
    vat_number        text,
    is_legacy         boolean not null default false,
    created_at        timestamptz not null default now(),
    created_by        uuid references public.profiles(id) on delete set null,
    constraint vat_policies_rate_valid
        check (configured_rate > 0 and configured_rate <= 1),
    constraint vat_policies_number_normalized
        check (vat_number is null or (vat_number = btrim(vat_number) and length(vat_number) > 0)),
    constraint vat_policies_enabled_number_required
        check (not enabled or vat_number is not null or is_legacy)
);

create unique index vat_policies_one_legacy_idx
    on public.vat_policies ((is_legacy))
    where is_legacy;

alter table public.vat_policies enable row level security;

revoke all on table public.vat_policies from public, anon, authenticated, service_role;
grant select on table public.vat_policies to authenticated;
grant select on table public.vat_policies to service_role;

create policy read_vat_policies_for_active_staff
    on public.vat_policies
    for select
    to authenticated
    using (
        exists (
            select 1
            from public.profiles
            where profiles.id = (select auth.uid())
              and profiles.is_active
        )
    );

create or replace function public.prevent_vat_policy_mutation()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
    -- Preserve the declared ON DELETE SET NULL behavior for actor cleanup. The
    -- fiscal policy fields remain byte-for-byte unchanged.
    if tg_op = 'UPDATE'
       and old.created_by is not null
       and new.created_by is null
       and new.id = old.id
       and new.enabled is not distinct from old.enabled
       and new.configured_rate is not distinct from old.configured_rate
       and new.vat_number is not distinct from old.vat_number
       and new.is_legacy is not distinct from old.is_legacy
       and new.created_at is not distinct from old.created_at then
        return new;
    end if;

    raise exception 'VAT policies are immutable';
end;
$$;

revoke execute on function public.prevent_vat_policy_mutation()
    from public, anon, authenticated, service_role;

create trigger trg_vat_policies_immutable
    before update or delete on public.vat_policies
    for each row execute function public.prevent_vat_policy_mutation();

-- One deterministic resolver is shared by migration initialization and its
-- acceptance fixtures. It accepts raw JSON settings so missing, invalid and
-- valid pre-migration states can be tested without deriving expectations from
-- rows the migration itself created.
create or replace function private.resolve_vat_policy_preparation(
    p_rate jsonb,
    p_vat_number jsonb
)
returns table (configured_rate numeric(7,6), vat_number text)
language plpgsql
immutable
security invoker
set search_path = ''
as $$
declare
    v_rate_text text := p_rate #>> '{}';
    v_number_text text := p_vat_number #>> '{}';
begin
    configured_rate := 0.15;
    if v_rate_text is not null
       and pg_catalog.btrim(v_rate_text) ~ '^[+]?([0-9]+([.][0-9]*)?|[.][0-9]+)$'
       and pg_catalog.btrim(v_rate_text)::numeric > 0
       and pg_catalog.btrim(v_rate_text)::numeric <= 1 then
        configured_rate := pg_catalog.btrim(v_rate_text)::numeric(7,6);
    end if;

    vat_number := nullif(pg_catalog.btrim(v_number_text), '');
    return next;
end;
$$;

revoke execute on function private.resolve_vat_policy_preparation(jsonb, jsonb)
    from public, anon, authenticated, service_role;

-- Add the snapshot columns as nullable first. The backfill below establishes
