-- One shared calculation supplies the live X-read and the Z close. Gross
-- turnover remains the existing z_totals figure; this helper replaces only VAT
-- output with frozen enabled transaction bands and their copied returns.
create or replace function private.shift_vat_snapshot(
    p_shift_id integer,
    p_as_at timestamptz
)
returns jsonb
language sql
stable
security invoker
set search_path = ''
as $$
    with tax_parts as (
        select
            s.vat_policy_id as policy_id,
            s.vat_rate,
            s.vat_number,
            s.total - s.vat_amount as net,
            s.vat_amount as vat
        from public.sales s
        where s.shift_id = p_shift_id
          and s.status in ('completed', 'refunded')
          and s.sale_date <= p_as_at
          and s.vat_enabled

        union all

        select
            cn.vat_policy_id,
            cn.vat_rate,
            cn.vat_number,
            -(cn.total - cn.vat_amount),
            -cn.vat_amount
        from public.credit_notes cn
        where cn.shift_id = p_shift_id
          and cn.created_at <= p_as_at
          and cn.vat_enabled
    ),
    bands as (
        select
            vat_rate,
            pg_catalog.round(pg_catalog.sum(net), 2) as excl,
            pg_catalog.round(pg_catalog.sum(vat), 2) as vat,
            pg_catalog.round(pg_catalog.sum(net) + pg_catalog.sum(vat), 2) as incl
        from tax_parts
        group by vat_rate
    ),
    identities as (
        select distinct policy_id, vat_rate, vat_number
        from tax_parts
    )
    select pg_catalog.jsonb_build_object(
        'vat_total', coalesce((select pg_catalog.round(pg_catalog.sum(vat), 2) from tax_parts), 0),
        'vat', coalesce((
            select pg_catalog.jsonb_agg(
                pg_catalog.jsonb_build_object(
                    'rate', b.vat_rate * 100,
                    'label', case
                        when b.vat_rate = 0 then 'Zero-rated 0.00%'
                        else 'VAT ' || pg_catalog.to_char(b.vat_rate * 100, 'FM990.00') || '%'
                    end,
                    'excl', b.excl,
                    'vat', b.vat,
                    'incl', b.incl
                )
                order by b.vat_rate desc
            )
            from bands b
        ), '[]'::jsonb),
        'vat_identities', coalesce((
            select pg_catalog.jsonb_agg(
                pg_catalog.jsonb_build_object(
                    'policyId', i.policy_id,
                    'rate', i.vat_rate,
                    'vatNumber', i.vat_number
                )
                order by i.policy_id
            )
            from identities i
        ), '[]'::jsonb)
    );
$$;

revoke execute on function private.shift_vat_snapshot(integer, timestamptz)
    from public, anon, authenticated, service_role;

-- Keep every mature non-VAT section of z_totals unchanged. Its old derived VAT
-- block is overwritten by the helper at the return boundary, and the last
-- current-settings read is removed so historical reads have no policy pointer.
do $$
declare
    v_def text;
    v_old_setting text :=
        '    SELECT coalesce((value #>> ''{}'')::NUMERIC, 0.15) INTO v_default_vat' || chr(10)
        || '      FROM settings WHERE key = ''vat_rate'';' || chr(10)
        || '    IF v_default_vat IS NULL THEN v_default_vat := 0.15; END IF;';
    v_old_return text :=
        '        ''credited'',       round(v_credited, 2)' || chr(10)
        || '    );' || chr(10)
        || 'END;';
    v_new_return text :=
        '        ''credited'',       round(v_credited, 2)' || chr(10)
        || '    ) || private.shift_vat_snapshot(p_shift_id, p_as_at);' || chr(10)
        || 'END;';
begin
    select pg_catalog.replace(
        pg_catalog.pg_get_functiondef(p.oid),
        chr(13) || chr(10),
        chr(10)
    ) into v_def
    from pg_catalog.pg_proc p
    where p.proname = 'z_totals'
      and p.pronamespace = 'public'::pg_catalog.regnamespace;

    if v_def is null
       or pg_catalog.strpos(v_def, v_old_setting) = 0
       or pg_catalog.strpos(v_def, v_old_return) = 0 then
        raise exception 'z_totals does not match the expected pre-VAT report definition';
    end if;

    v_def := pg_catalog.replace(
        v_def,
        v_old_setting,
        '    v_default_vat := 0; -- compatibility variable; frozen output is merged below'
    );
    v_def := pg_catalog.replace(v_def, v_old_return, v_new_return);
    execute v_def;
end;
$$;

-- Replace daily_summary as one snapshot-driven query. Running the mature body
-- and overwriting its VAT JSON at the return boundary still executes its old
-- tax-band calculation. Keeping the non-tax CTEs here preserves the public
-- report contract while ensuring no historical read consults or derives a
-- current policy/rate, even when the settings rows are absent.
create or replace function public.daily_summary(p_from date, p_to date)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
    v_out jsonb;
begin
    if p_from is null or p_to is null then
        raise exception 'daily_summary needs a from and a to date';
    end if;
    if p_to < p_from then
        raise exception 'daily_summary: % is before %', p_to, p_from;
    end if;
    if p_to - p_from > 400 then
        raise exception 'daily_summary: range is longer than 400 days';
    end if;

    with
    scoped as (
        select
            s.id,
            (s.sale_date at time zone 'Indian/Mauritius')::date as day,
            s.total,
            s.vat_amount as vat,
            coalesce(pr.full_name, 'Unknown') as cashier,
            s.customer_id
        from public.sales s
        left join public.profiles pr on pr.id = s.cashier_id
        where s.status = 'completed'
          and (s.sale_date at time zone 'Indian/Mauritius')::date between p_from and p_to
    ),
    tax_parts as (
        select
            (s.sale_date at time zone 'Indian/Mauritius')::date as day,
            pg_catalog.to_char(
                pg_catalog.round(s.vat_rate * 100, 2),
                'FM990.00'
            ) as rate,
            s.total as incl,
            s.vat_amount as vat
        from public.sales s
        where s.status in ('completed', 'refunded')
          and s.vat_enabled
          and (s.sale_date at time zone 'Indian/Mauritius')::date between p_from and p_to

        union all

        select
            (cn.created_at at time zone 'Indian/Mauritius')::date,
            pg_catalog.to_char(
                pg_catalog.round(cn.vat_rate * 100, 2),
                'FM990.00'
            ),
            -cn.total,
            -cn.vat_amount
        from public.credit_notes cn
        where cn.vat_enabled
          and (cn.created_at at time zone 'Indian/Mauritius')::date between p_from and p_to
    ),
    lines as (
        select
            sc.day,
            si.qty,
            coalesce(nullif(pg_catalog.btrim(cat.name), ''), '(uncategorised)') as category,
            si.line_total
              * case when t.line_sum > 0 then sc.total / t.line_sum else 1 end as amount
        from public.sale_items si
        join scoped sc on sc.id = si.sale_id
        join (
            select si2.sale_id, pg_catalog.sum(si2.line_total) as line_sum
            from public.sale_items si2
            where si2.sale_id in (select id from scoped)
            group by si2.sale_id
        ) t on t.sale_id = si.sale_id
        left join public.product_variants pv on pv.id = si.variant_id
        left join public.products p on p.id = pv.product_id
        left join public.categories cat on cat.id = p.category_id
    ),
    pays as (
        select sc.day, sp.method, sp.amount
        from public.sale_payments sp
        join scoped sc on sc.id = sp.sale_id
    ),
    headline as (
        select
            day,
            pg_catalog.count(*)::integer as tickets,
            pg_catalog.count(distinct customer_id)::integer as customers,
            pg_catalog.round(pg_catalog.sum(total), 2) as total_incl,
            pg_catalog.round(pg_catalog.sum(vat), 2) as vat,
            pg_catalog.round(pg_catalog.sum(total) - pg_catalog.sum(vat), 2) as total_excl,
            pg_catalog.round(pg_catalog.sum(total) / pg_catalog.count(*), 2) as avg_incl,
            pg_catalog.round(
                (pg_catalog.sum(total) - pg_catalog.sum(vat)) / pg_catalog.count(*),
                2
            ) as avg_excl
        from scoped
        group by day
    ),
    day_items as (
        select day, pg_catalog.sum(qty)::integer as items
        from lines
        group by day
    ),
    day_methods as (
        select
            day,
            pg_catalog.jsonb_object_agg(
                method,
                pg_catalog.jsonb_build_object(
                    'n', n,
                    'amount', pg_catalog.round(amount, 2)
                )
            ) as by_method
        from (
            select
                day,
                method,
                pg_catalog.count(*)::integer as n,
                pg_catalog.sum(amount) as amount
            from pays
            group by day, method
        ) m
        group by day
    ),
    day_taxes as (
        select
            day,
            pg_catalog.jsonb_object_agg(
                rate,
                pg_catalog.jsonb_build_object(
                    'incl', pg_catalog.round(incl, 2),
                    'excl', pg_catalog.round(incl - vat, 2),
                    'vat', pg_catalog.round(vat, 2)
                )
            ) as by_tax
        from (
            select
                day,
                rate,
                pg_catalog.sum(incl) as incl,
                pg_catalog.sum(vat) as vat
            from tax_parts
            group by day, rate
        ) t
        group by day
    ),
    day_sellers as (
        select
            day,
            pg_catalog.jsonb_object_agg(
                cashier,
                pg_catalog.jsonb_build_object(
                    'n', n,
                    'amount', pg_catalog.round(amount, 2)
                )
            ) as by_seller
        from (
            select
                day,
                cashier,
                pg_catalog.count(*)::integer as n,
                pg_catalog.sum(total) as amount
            from scoped
            group by day, cashier
        ) s
        group by day
    ),
    day_categories as (
        select
            day,
            pg_catalog.jsonb_object_agg(
                category,
                pg_catalog.jsonb_build_object(
                    'qty', qty,
                    'amount', pg_catalog.round(amount, 2)
                )
            ) as by_category
        from (
            select
                day,
                category,
                pg_catalog.sum(qty)::integer as qty,
                pg_catalog.sum(amount) as amount
            from lines
            group by day, category
        ) c
        group by day
    ),
    cols as (
        select
            (
                select coalesce(
                    pg_catalog.jsonb_agg(distinct method order by method),
                    '[]'::jsonb
                )
                from pays
            ) as methods,
            (
                select coalesce(
                    pg_catalog.jsonb_agg(distinct rate order by rate),
                    '[]'::jsonb
                )
                from tax_parts
            ) as taxes,
            (
                select coalesce(
                    pg_catalog.jsonb_agg(distinct cashier order by cashier),
                    '[]'::jsonb
                )
                from scoped
            ) as sellers,
            (
                select coalesce(
                    pg_catalog.jsonb_agg(distinct category order by category),
                    '[]'::jsonb
                )
                from lines
            ) as categories
    )
    select pg_catalog.jsonb_build_object(
        'from', p_from,
        'to', p_to,
        'rows', coalesce((
            select pg_catalog.jsonb_agg(
                pg_catalog.jsonb_build_object(
                    'day', h.day,
                    'tickets', h.tickets,
                    'items', coalesce(di.items, 0),
                    'customers', h.customers,
                    'total_incl', h.total_incl,
                    'vat', h.vat,
                    'total_excl', h.total_excl,
                    'avg_incl', h.avg_incl,
                    'avg_excl', h.avg_excl,
                    'by_method', coalesce(dm.by_method, '{}'::jsonb),
                    'by_tax', coalesce(dt.by_tax, '{}'::jsonb),
                    'by_seller', coalesce(ds.by_seller, '{}'::jsonb),
                    'by_category', coalesce(dc.by_category, '{}'::jsonb)
                )
                order by h.day
            )
            from headline h
            left join day_items di on di.day = h.day
            left join day_methods dm on dm.day = h.day
            left join day_taxes dt on dt.day = h.day
            left join day_sellers ds on ds.day = h.day
            left join day_categories dc on dc.day = h.day
        ), '[]'::jsonb),
        'methods', (select methods from cols),
        'taxes', (select taxes from cols),
        'sellers', (select sellers from cols),
        'categories', (select categories from cols)
    ) into v_out;

    return v_out;
end;
$$;

revoke execute on function public.daily_summary(date, date) from public, anon;
grant execute on function public.daily_summary(date, date) to authenticated;

-- Freeze the exact live identity array in its dedicated column. The stored
-- totals object deliberately drops the new live-only key, preserving the
-- historical Z JSON contract; readers combine the separate frozen column.
create or replace function public.close_shift_z(
    p_shift_id integer,
    p_counted_cash numeric,
    p_notes text default null
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_now timestamptz := pg_catalog.now();
    v_totals jsonb;
    v_identities jsonb;
    v_expected numeric;
    v_variance numeric;
    v_counted numeric := pg_catalog.round(coalesce(p_counted_cash, 0), 2);
    v_z_no text;
    v_z_id bigint;
    v_user uuid := auth.uid();
begin
    perform 1
    from public.shifts
    where id = p_shift_id and closed_at is null
    for update;
    if not found then
        raise exception 'That shift is already closed, or does not exist';
    end if;

    v_totals := public.z_totals(p_shift_id, v_now);
    v_identities := coalesce(v_totals -> 'vat_identities', '[]'::jsonb);
    v_expected := (v_totals ->> 'expected_cash')::numeric;
    v_variance := pg_catalog.round(v_counted - v_expected, 2);

    update public.shifts
    set closed_by = v_user,
        closed_at = v_now,
        counted_cash = v_counted,
        expected_cash = v_expected,
        variance = v_variance,
        notes = p_notes
    where id = p_shift_id;

    v_z_no := public.next_z_no();

    insert into public.z_reports (
        shift_id, z_no, closed_at, closed_by,
        counted_cash, expected_cash, variance, totals, vat_identity_snapshot
    ) values (
        p_shift_id, v_z_no, v_now, v_user,
        v_counted, v_expected, v_variance,
        v_totals - 'vat_identities', v_identities
    ) returning id into v_z_id;

    return pg_catalog.jsonb_build_object(
        'z_id', v_z_id,
        'z_no', v_z_no,
        'counted_cash', v_counted,
        'expected_cash', v_expected,
        'variance', v_variance,
        'totals', v_totals,
        'vat_identity_snapshot', v_identities
    );
end;
$$;

commit;
