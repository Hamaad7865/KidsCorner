-- ============================================================
-- Kids Corner — immutable VAT registration policies
--
-- A policy row is an append-only fiscal decision. Documents retain the exact
-- policy identity and values in force when they were created; settings are
-- only the prepared pointer values used to create the next policy.
-- ============================================================

begin;

create schema if not exists private;
revoke all on schema private from public, anon, authenticated, service_role;

create table public.vat_policies (
    id                bigint generated by default as identity primary key,
    enabled           boolean not null,
    configured_rate   numeric(7,6) not null,
    vat_number        text,
    is_legacy         boolean not null default false,
    created_at        timestamptz not null default now(),
    created_by        uuid references public.profiles(id) on delete set null,
    constraint vat_policies_rate_valid
        check (configured_rate > 0 and configured_rate <= 1),
    constraint vat_policies_number_normalized
        check (vat_number is null or (vat_number = btrim(vat_number) and length(vat_number) > 0)),
    constraint vat_policies_enabled_number_required
        check (not enabled or vat_number is not null or is_legacy)
);

create unique index vat_policies_one_legacy_idx
    on public.vat_policies ((is_legacy))
    where is_legacy;

alter table public.vat_policies enable row level security;

revoke all on table public.vat_policies from public, anon, authenticated, service_role;
grant select on table public.vat_policies to authenticated;
grant select on table public.vat_policies to service_role;

