create or replace function public.prevent_vat_policy_mutation()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
    -- Preserve the declared ON DELETE SET NULL behavior for actor cleanup. The
    -- fiscal policy fields remain byte-for-byte unchanged.
    if tg_op = 'UPDATE'
       and old.created_by is not null
       and new.created_by is null
       and new.id = old.id
       and new.enabled is not distinct from old.enabled
       and new.configured_rate is not distinct from old.configured_rate
       and new.vat_number is not distinct from old.vat_number
       and new.is_legacy is not distinct from old.is_legacy
       and new.created_at is not distinct from old.created_at then
        return new;
    end if;

    raise exception 'VAT policies are immutable';
end;
$$;

revoke execute on function public.prevent_vat_policy_mutation()
    from public, anon, authenticated, service_role;

create trigger trg_vat_policies_immutable
    before update or delete on public.vat_policies
    for each row execute function public.prevent_vat_policy_mutation();

-- One deterministic resolver is shared by migration initialization and its
-- acceptance fixtures. It accepts raw JSON settings so missing, invalid and
-- valid pre-migration states can be tested without deriving expectations from
-- rows the migration itself created.
create or replace function private.resolve_vat_policy_preparation(
    p_rate jsonb,
    p_vat_number jsonb
)
returns table (configured_rate numeric(7,6), vat_number text)
language plpgsql
immutable
security invoker
set search_path = ''
as $$
declare
    v_rate_text text := p_rate #>> '{}';
    v_number_text text := p_vat_number #>> '{}';
begin
    configured_rate := 0.15;
    if v_rate_text is not null
       and pg_catalog.btrim(v_rate_text) ~ '^[+]?([0-9]+([.][0-9]*)?|[.][0-9]+)$'
       and pg_catalog.btrim(v_rate_text)::numeric > 0
       and pg_catalog.btrim(v_rate_text)::numeric <= 1 then
        configured_rate := pg_catalog.btrim(v_rate_text)::numeric(7,6);
    end if;

    vat_number := nullif(pg_catalog.btrim(v_number_text), '');
    return next;
end;
$$;

revoke execute on function private.resolve_vat_policy_preparation(jsonb, jsonb)
    from public, anon, authenticated, service_role;

