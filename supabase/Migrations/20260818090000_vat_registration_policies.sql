alter table public.purchases
    add constraint purchases_vat_policy_id_fkey
        foreign key (vat_policy_id) references public.vat_policies(id),
    add constraint purchases_vat_rate_valid
        check (vat_rate is null or (vat_rate > 0 and vat_rate <= 1)),
    add constraint purchases_vat_amount_valid check (vat_amount is null or vat_amount >= 0),
    add constraint purchases_vat_snapshot_for_received check (
        (status = 'received'
          and vat_policy_id is not null
          and vat_enabled is not null
          and vat_rate is not null
          and vat_amount is not null)
        or
        (status in ('draft', 'cancelled')
          and vat_policy_id is null
          and vat_enabled is null
          and vat_rate is null
          and vat_amount is null)
    );

alter table public.z_reports
    alter column vat_identity_snapshot set default '[]'::jsonb,
    alter column vat_identity_snapshot set not null,
    add constraint z_reports_vat_identity_array
        check (jsonb_typeof(vat_identity_snapshot) = 'array');

-- The generic settings path remains available to owners, except for the three
-- values whose atomic policy/audit contract is enforced by set_vat_policy.
drop policy if exists manage on public.settings;
create policy manage on public.settings
    for all
    to authenticated
    using (
        public.current_role_of_user() = 'owner'
        and key not in ('vat_enabled', 'vat_rate', 'vat_number')
    )
    with check (
        public.current_role_of_user() = 'owner'
        and key not in ('vat_enabled', 'vat_rate', 'vat_number')
    );

create or replace function public.set_vat_policy(
    p_enabled boolean,
    p_configured_rate numeric,
    p_vat_number text
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_actor uuid := auth.uid();
    v_number text := nullif(pg_catalog.btrim(p_vat_number), '');
    v_rate numeric(7,6);
    v_old public.vat_policies%rowtype;
    v_new_id bigint;
begin
    if not exists (
        select 1
        from public.profiles
        where id = v_actor
          and role = 'owner'
          and is_active
    ) then
        raise insufficient_privilege using message = 'Only an active owner can change VAT policy';
    end if;

    perform pg_catalog.pg_advisory_xact_lock(20260818090000);

    if p_configured_rate is null or p_configured_rate <= 0 or p_configured_rate > 1 then
        raise check_violation using message = 'Configured VAT rate must be greater than zero and at most one';
    end if;
    v_rate := p_configured_rate::numeric(7,6);
    if v_rate <= 0 or v_rate > 1 then
        raise check_violation using message = 'Configured VAT rate must be greater than zero and at most one';
    end if;
    if p_enabled is null then
        raise not_null_violation using message = 'VAT enabled state is required';
    end if;
    if p_enabled and v_number is null then
        raise check_violation using message = 'A VAT number is required when VAT is enabled';
    end if;

    select * into strict v_old
    from public.vat_policies
    order by id desc
    limit 1;

    insert into public.vat_policies (
        enabled, configured_rate, vat_number, is_legacy, created_by
    ) values (
        p_enabled, v_rate, v_number, false, v_actor
    )
    returning id into v_new_id;

    insert into public.settings (key, value) values
        ('vat_enabled', pg_catalog.to_jsonb(p_enabled)),
        ('vat_rate', pg_catalog.to_jsonb(v_rate)),
        ('vat_number', coalesce(pg_catalog.to_jsonb(v_number), 'null'::jsonb))
    on conflict (key) do update set value = excluded.value;

    insert into public.audit_events (
        actor_id, event_type, ref_type, ref_id, summary, detail
    ) values (
        v_actor,
        'setting.changed',
        'setting',
        'vat_policy',
        'VAT policy changed',
        pg_catalog.jsonb_build_object(
            'old', pg_catalog.jsonb_build_object(
                'enabled', v_old.enabled,
                'rate', v_old.configured_rate,
                'vatNumber', v_old.vat_number
            ),
            'new', pg_catalog.jsonb_build_object(
                'enabled', p_enabled,
                'rate', v_rate,
                'vatNumber', v_number
            )
        )
    );

    return v_new_id;
end;
$$;

revoke execute on function public.set_vat_policy(boolean, numeric, text) from public;
revoke execute on function public.set_vat_policy(boolean, numeric, text) from anon;
revoke execute on function public.set_vat_policy(boolean, numeric, text) from service_role;
grant execute on function public.set_vat_policy(boolean, numeric, text) to authenticated;

commit;
